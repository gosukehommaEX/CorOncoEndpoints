test_that("accrual intervals from rates, proportions and interval lengths", {
  # 10 per month on [0, 6), then 20 per month until 200 patients (month 13)
  a <- .accrual_setup(c(0, 6), c(10, 20), NULL, 200)
  expect_equal(a$time, c(0, 6, 13))
  expect_equal(a$prob, c(0.3, 0.7))
  expect_equal(a$cum, c(0, 0.3, 1))
  b <- .accrual_setup(c(0, 6, 24), c(5, 15), NULL, 300)
  expect_equal(b$time, c(0, 6, 24))
  expect_equal(b$prob, c(0.1, 0.9))
  p <- .accrual_setup(c(0, 6, 24), NULL, c(1, 3), 50)
  expect_equal(p$prob, c(0.25, 0.75))
  u <- .accrual_setup(c(2, 6, 14), NULL, NULL, 50)
  expect_equal(u$prob, c(4, 8) / 12)
  expect_equal(u$cum, c(0, 1 / 3, 1))
  s <- .accrual_setup(0, 25, NULL, 100)
  expect_equal(s$time, c(0, 4))
  expect_equal(s$prob, 1)
  z <- .accrual_setup(NULL, NULL, NULL, 10)
  expect_equal(z$time, 0)
  expect_length(z$prob, 0)
})

test_that("inconsistent accrual specifications give errors", {
  expect_error(.accrual_setup(c(0, 6, 24), c(1, 3), NULL, 100), "accrues 60")
  expect_error(.accrual_setup(c(0, 12), c(10, 1), NULL, 100), "already accrue")
  expect_error(.accrual_setup(c(0, 12), c(10, 0), NULL, 200), "positive")
  expect_error(.accrual_setup(c(0, 12), 5, 1, 60), "at most one")
  expect_error(.accrual_setup(c(0, 12, 24), c(1, 2, 3, 4), NULL, 60), "length")
  expect_error(.accrual_setup(-1, 5, NULL, 60), "non-negative")
  expect_error(.accrual_setup(NULL, 5, NULL, 60), "require")
})
