test_that("pieces and cumulative hazards of the dropout distribution", {
  d <- .dropout_setup(c(0.1, 0.02), NULL, c(0, 6, Inf), k = 2)
  expect_length(d, 2)
  expect_equal(d[[2]]$time, c(0, 6))
  expect_equal(d[[2]]$hazard, c(0.1, 0.02))
  expect_equal(d[[2]]$cum, c(0, 0.6))
  e <- .dropout_setup(c(0.01, 0.03), NULL, NULL, k = 2)
  expect_equal(e[[2]]$hazard, 0.03)
  expect_equal(e[[2]]$time, 0)
  m <- .dropout_setup(0, list(Inf, 12), NULL, k = 2)
  expect_equal(m[[1]]$hazard, 0)
  expect_equal(m[[2]]$hazard, log(2) / 12)
  l <- .dropout_setup(list(c(0.1, 0.02), 0.05), NULL, list(c(0, 6, Inf), NULL), k = 2)
  expect_equal(l[[1]]$cum, c(0, 0.6))
  expect_equal(l[[2]]$hazard, 0.05)
})

test_that("invalid dropout specifications give errors", {
  expect_error(.dropout_setup(0.1, 5, NULL, k = 1), "at most one")
  expect_error(.dropout_setup(c(0.1, 0.2), NULL, NULL, k = 1), "one per group")
  expect_error(.dropout_setup(c(0.1, 0.2), NULL, c(1, 6, Inf), k = 1), "start at 0")
  expect_error(.dropout_setup(0.1, NULL, c(0, 6, Inf), k = 1), "length")
  expect_error(.dropout_setup(list(0.1), NULL, NULL, k = 2), "one element per group")
})
